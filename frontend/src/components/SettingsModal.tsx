export function SettingsModal(props: { onClose: () => void }) {
  const status = useStore((s) => s.status);
  const showToast = useStore((s) => s.showToast);
  const initial = status?.risk?.config;
  const [draft, setDraft] = useState<Record<string, string>>(() => {
    const d: Record<string, string> = {};
    if (initial) {
      for (const f of FIELDS) d[f.key] = String(initial[f.key]);
    }
    return d;
  });
  const [saving, setSaving] = useState(false);

  async function save() {
    const payload: Record<string, number> = {};
    for (const f of FIELDS) {
      const v = Number(draft[f.key]);
      if (!Number.isFinite(v)) {
        showToast("error", `Invalid value for ${f.label}`);
        return;
      }
      payload[f.key] = v;
    }
    setSaving(true);
    try {
      await api.updateRisk(payload);
      const s = await api.status();
      useStore.getState().setStatus(s);
      showToast("info", "Risk settings saved");
      props.onClose();
    } catch (e) {
      showToast("error", (e as Error).message);
    } finally {
      setSaving(false);
    }
  }

  return (
    <Modal title="Settings — Risk & Engine" onClose={props.onClose}>
      <div className="modal-body">
        <div className="form-grid">
          {FIELDS.map((f) => (
            <div className="field" key={f.key} title={f.help}>
              <label style={{ display: "flex", alignItems: "center", gap: "4px", cursor: "help" }}>
                {f.label} <span style={{ color: "var(--faint)" }}>ⓘ</span>
              </label>
              <input
                type="number"
                className="num"
                step={f.step ?? 1}
                value={draft[f.key] ?? ""}
                onChange={(e) => setDraft({ ...draft, [f.key]: e.target.value })}
              />
              <span className="hint">{f.hint}</span>
            </div>
          ))}
        </div>

        <div style={{ marginTop: 18, borderTop: "1px solid var(--border)", paddingTop: 12 }}>
          <label style={{ display: "block", marginBottom: 6, fontWeight: 600, fontSize: 13 }}>
            UI Heartbeat Indicator Style
          </label>
          <select
            value={useStore.getState().heartbeatStyle}
            onChange={(e) => useStore.getState().setHeartbeatStyle(e.target.value as any)}
            style={{ width: "100%", padding: "6px 10px" }}
          >
            <option value="ekg">EKG Waveform + Status Dot (Recommended Default)</option>
            <option value="heart">EKG Waveform + Micro Heart + Status Dot</option>
            <option value="minimal">Minimal Status Dot Only</option>
            <option value="off">Off (Disable Heartbeat Indicator)</option>
          </select>
          <span className="hint" style={{ marginTop: 4, display: "block" }}>
            Controls the real-time event-driven telemetry indicator in the top header bar.
          </span>
        </div>

        <div style={{ marginTop: 18, borderTop: "1px solid var(--border)", paddingTop: 12 }}>
          <div className="muted" style={{ fontSize: 12, lineHeight: 1.7 }}>
            <b>Environment</b> (from <span className="mono">.env</span>, restart to change):
            data provider <b>{status?.provider ?? "—"}</b> · broker <b>{status?.broker ?? "auto"}</b> ·
            Alpaca keys <b>{status?.has_alpaca_keys ? "configured" : "not set"}</b> ·
            live trading <b>{status?.live_trading_enabled ? "ENABLED" : "disabled"}</b>
            <br />
            AI model: <b>{status?.model.trained ? `trained (${status.model.samples} samples)` : "heuristic (untrained)"}</b>
          </div>
        </div>
      </div>
      <div className="modal-foot">
        <button className="btn ghost" onClick={props.onClose}>Cancel</button>
        <button className="btn primary" onClick={save} disabled={saving}>
          {saving ? "Saving…" : "Save settings"}
        </button>
      </div>
    </Modal>
  );
}
